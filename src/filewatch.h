/* "Has this file just been written?" for save states, without a thread.
 *
 * The core writes a state on a worker thread: it creates (truncates) the file, writes for a while and closes it.  An
 * inotify watch on the file's directory for IN_CLOSE_WRITE | IN_MOVED_TO with the file's name reports exactly the moment
 * the writer is done, whatever the file system (the events are generated by the VFS: vfat, ext4, btrfs alike).  The
 * descriptor is non-blocking and polled from the per-frame hook.
 *
 * If inotify is not available (inotify_init1 or inotify_add_watch fails) the module falls back to looking at the file:
 * it counts as written when its modification time or size differs from what it was at filewatch_start() and it has
 * stopped changing for FILEWATCH_SETTLE_MS.
 */

#ifndef FILEWATCH_H
#define FILEWATCH_H

#include <limits.h>
#include <stdint.h>
#include <sys/stat.h>
#include <time.h>

#define FILEWATCH_SETTLE_MS 300u

typedef struct {
    int             fd;                  /* inotify descriptor, -1 = polling the file */
    int             wd;
    char            path[PATH_MAX];
    char            name[256];           /* the file's name in the watched directory */
    /* the file as it was at start (always taken: inotify queue overflow falls back to it too) */
    int             before_exists;
    struct timespec before_mtime;
    off_t           before_size;
    /* fallback: the size seen last and since when */
    off_t           last_size;
    int             last_valid;
    uint32_t        last_change_ms;
} filewatch;

/* Starts watching `path` (the file may or may not exist yet).  force_polling = 1 skips inotify (tests).  Always succeeds
 * unless the path is unusable (-1).  Call it BEFORE the write is requested. */
int  filewatch_start(filewatch *w, const char *path, int force_polling);
/* 1 once the file was written/replaced since filewatch_start(), else 0.  Never blocks. */
int  filewatch_poll(filewatch *w);
void filewatch_stop(filewatch *w);
int  filewatch_uses_inotify(const filewatch *w);

#endif /* FILEWATCH_H */
