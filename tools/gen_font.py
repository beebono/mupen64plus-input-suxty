#!/usr/bin/env python3
# Generates src/font_data.c: 8x16 (items) and 12x24 (hints, integer scale only) ASCII atlases from DejaVu Sans Mono Bold.
# Cells 95..98 are the down, up, left, right arrows (control chars \x01..\x04); the last cell is solid white.
# usage: tools/gen_font.py [path/to/DejaVuSansMono-Bold.ttf] > src/font_data.c
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
COLS, ROWS = 16, 8
ARROWS = {95: "↓", 96: "↑", 97: "←", 98: "→"}


def make_atlas(cw, ch, size):
    font = ImageFont.truetype(ttf, size)
    big = ImageFont.truetype(ttf, size * 4)      # supersample for decent AA at tiny size
    atlas = Image.new("L", (cw * COLS, ch * ROWS), 0)
    asc, desc = font.getmetrics()

    def glyph(cell, text):
        img = Image.new("L", (cw * 4, ch * 4), 0)
        d = ImageDraw.Draw(img)
        w = d.textlength(text, font=big)
        d.text(((cw * 4 - w) / 2, (ch * 4 - (asc + desc) * 4) / 2 + 0), text, font=big, fill=255)
        atlas.paste(img.resize((cw, ch), Image.LANCZOS), ((cell % COLS) * cw, (cell // COLS) * ch))

    for code in range(32, 127):
        glyph(code - 32, chr(code))
    for cell, text in ARROWS.items():
        glyph(cell, text)
    last = COLS * ROWS - 1
    atlas.paste(255, ((last % COLS) * cw, (last // COLS) * ch, (last % COLS) * cw + cw, (last // COLS) * ch + ch))
    return atlas


def emit(out, name, atlas, cw, ch):
    data = atlas.tobytes()
    out.append("/* %dx%d cells, atlas %dx%d, 8-bit alpha */" % (cw, ch, atlas.width, atlas.height))
    out.append("const unsigned char %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 24):
        out.append("    " + ",".join("%d" % b for b in data[i:i + 24]) + ",")
    out.append("};")


out = ["/* GENERATED by tools/gen_font.py - do not edit.\n"
       " * Anti-aliased ASCII font atlases (8x16 and 12x24), glyph shapes rasterised from\n"
       " * DejaVu Sans Mono Bold (Bitstream Vera licence). */\n",
       '#include "font.h"\n']
emit(out, "font_atlas_alpha", make_atlas(8, 16, 13), 8, 16)
emit(out, "font_atlas_alpha_12x24", make_atlas(12, 24, 20), 12, 24)
sys.stdout.write("\n".join(out) + "\n")
